import pandas as pd

df_ = pd.read_csv("Tweets.csv")

df_.head()

df = df_[["airline_sentiment", "text"]].copy()

df

df["airline_sentiment"].hist()

df = df[df.airline_sentiment != 'neutral'].copy()

df

target_map = { 'positive': 1, 'negative': 0 }

df['target'] = df.airline_sentiment.map(target_map)

df

texts = df['text'].tolist()

predictions = classifier(texts)

predictions

probs = [d['score'] if d['label'].startswith('P') else 1 - d['score'] \
         for d in predictions]

probs

preds = [1 if d['label'].startswith('P') else 0
         for d in predictions]

preds

import numpy as np

preds = np.array(preds)

preds



print("acc: ", np.mean(df['target'] == preds))

count = ((df['target'] == 0) & (preds == 1)).sum()
print(count)

from sklearn.metrics import confusion_matrix, f1_score, roc_auc_score

labels = [0, 1]
cm = confusion_matrix(df['target'], preds)

print(cm)

f1_score(df['target'], preds)

f1_score(1 - df['target'], 1 - preds)

