def align_targets(labels, word_ids):
  aligned_labels = []
  last_word = None
  for word in word_ids:
    if word is None:
      label = -100
    elif word != last_word:
      label = labels[word]
    else:
      label = labels[word]

      if label in begin2inside:
        label = begin2inside[label]

    aligned_labels.append(label)
    last_word = word

  return aligned_labels

