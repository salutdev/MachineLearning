import numpy as np

def compute_metrics(logits_and_labels):
  logits, labels = logits_and_labels
  preds = np.argmax(logits, axis=-1)

  jagged_labels = [[t for t in label if t != -100] for label in labels]
  jagged_preds = [[p for p, t in zip(pred, targ) if t != -100] for pred, targ in zip(preds, labels)]

  flattened_labels = np.concatenate(jagged_labels).tolist()
  flattened_preds = np.concatenate(jagged_preds).tolist()

  accuracy = accuracy_metric.compute(predictions=flattened_preds, references=flattened_labels)
  # accuracy = accuracy_score(predictions=flattened_preds, references=flattened_labels)
  precision = precision_metric.compute(predictions=flattened_preds, references=flattened_labels, average='macro')
  recall = recall_metric.compute(predictions=flattened_preds, references=flattened_labels, average='macro')
  f1 = f1_metric.compute(predictions=flattened_preds, references=flattened_labels, average='macro')

  return {
      'accuracy': accuracy,
      'precision': precision,
      'recall': recall,
      'f1': f1,
  }

